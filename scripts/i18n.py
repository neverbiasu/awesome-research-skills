def load(lang, skills):
    """id -> translated description, only where the English source is unchanged."""
    path = f"data/i18n/{lang}.tsv"
    if not os.path.exists(path):
        return {}
    src = json.load(open("data/i18n/src.json"))
    cur = {e["id"]: e["description"] for e in skills}
    out = {}
    for line in open(path, encoding="utf-8"):
        if "\t" in line:
            i, t = line.rstrip("\n").split("\t", 1)
            if cur.get(i) is not None and src.get(i) == cur[i]:
                out[i] = t
    return out


def render_all(skills, by_cat, categories, title_line, url_of, stats):
    """Write every localized README; return {lang: untranslated-entry-count}."""
    missing = {}
    for lang, fname in FILES.items():
        ui, tr = UI[lang], load(lang, skills)
        missing[lang] = len(skills) - len(tr)
        out = [title_line, switcher(lang) + "\n", "> " + ui["tagline"] + "\n", ui["flow"] + "\n",
               ui["scope"].format(**stats) + "\n", ui["checks"].format(**stats) + "\n", ui["note"] + "\n", f"## {ui['contents']}\n"]
        for key, _, _ in categories:
            if key in by_cat:
                out.append(f"- [{ui['cats'][key][0]}](#{anchor(ui['cats'][key][0])})")
        out += [f"- [{ui['how']}](#{anchor(ui['how'])})", ""]
        for key, _, _ in categories:
            if key not in by_cat:
                continue
            out += [f"## {ui['cats'][key][0]}\n", f"*{ui['cats'][key][1]}*\n"]
            for e in by_cat[key]:  # README.md order
                tag = f" `{e['lang']}`" if e.get("lang") else ""
                out += [f"- [{e['name']}]({url_of(e)}){tag} - {tr.get(e['id'], e['description'])}", ""]
        out += [f"## {ui['how']}\n", ui["how1"] + "\n", ui["how2"].format(**stats) + "\n", ui["how3"].format(**stats) + "\n",
                ui["how4"] + "\n", f"## {ui['contrib']}\n", ui["contrib_body"] + "\n"]
        with open(fname, "w", encoding="utf-8") as f:
            f.write("\n".join(out))
    return missing


def anchor(title):
    import re
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
